"""Deterministic safe Lean module generator."""

from __future__ import annotations

import os
import re
import tempfile
from fractions import Fraction
from pathlib import Path

from leanverifier.canonicalize import canonicalize_rational, module_token
from leanverifier.errors import InvalidInputError
from leanverifier.manifest import ModelManifest, RequestManifest

_MODULE_RE = re.compile(r"^GeneratedModel_[0-9a-f]{16}$")


def _lean_rat(value: Fraction) -> str:
    s = canonicalize_rational(value)
    if "/" in s:
        num, den = s.split("/", 1)
        return f"({num} : Rat) / ({den} : Rat)"
    return f"({s} : Rat)"


def _lean_vec(values: list[Fraction]) -> str:
    """Emit an exact ``Fin n → Rat`` without ``![]`` / bang indexing.

    Matrix ``![…]`` notation requires extra Mathlib imports and is easy to
    misparse as boolean ``!``; Fin-pattern matches match the supported kernel.
    """
    if not values:
        return "(fun (_ : Fin 0) => (0 : Rat))"
    n = len(values)
    arms = "\n".join(
        f"    | ⟨{i}, _⟩ => {_lean_rat(v)}" for i, v in enumerate(values)
    )
    return f"(fun (i : Fin {n}) =>\n  match i with\n{arms})"


def render_module(
    model: ModelManifest,
    request: RequestManifest,
    *,
    module_name: str | None = None,
) -> tuple[str, str]:
    if model.dimension != request.dimension:
        raise InvalidInputError("model/request dimension mismatch")
    if request.model_digest != model.digest:
        raise InvalidInputError("request.model_digest does not match model")

    name = module_name or f"GeneratedModel_{module_token(model.digest)}"
    if not _MODULE_RE.fullmatch(name):
        raise InvalidInputError(f"illegal module name: {name}")

    weights = _lean_vec(model.weights)
    bias = _lean_rat(model.bias)
    xref = _lean_vec(request.reference_input)
    eps = _lean_rat(request.epsilon)

    source = f"""/-
  Auto-generated by LeanVerifier. Do not edit.
  model_digest: {model.digest}
  request_digest: {request.digest}
-/
import LeanVerifier.Theorem.AffineMarginRobustness

namespace {name}

open LeanVerifier AffineBinaryClassifier

def M : AffineBinaryClassifier {model.dimension} :=
  ⟨{weights}, {bias}⟩

def x : Vec {model.dimension} := {xref}

def eps : Rat := {eps}

theorem eps_nonneg : 0 ≤ eps := by native_decide

theorem margin_strict : eps * weightL1 M < |score M x| := by native_decide

theorem certified : LocallyRobustAt M x eps :=
  affine_margin_robustness M x eps eps_nonneg margin_strict

end {name}
"""
    return name, source


def _assert_safe_output_root(output_root: Path) -> Path:
    root = output_root.expanduser()
    if not root.is_absolute():
        raise InvalidInputError("output_root must be absolute")
    resolved = root.resolve(strict=False)
    if resolved.exists() and resolved.is_symlink():
        raise InvalidInputError("output_root must not be a symlink")
    if resolved.exists() and not resolved.is_dir():
        raise InvalidInputError("output_root must be a directory")
    return resolved


def write_module_atomic(
    model: ModelManifest,
    request: RequestManifest,
    output_root: Path,
    *,
    module_name: str | None = None,
) -> Path:
    root = _assert_safe_output_root(output_root)
    root.mkdir(parents=True, exist_ok=True)
    name, source = render_module(model, request, module_name=module_name)
    target = (root / f"{name}.lean").resolve(strict=False)
    if target.parent != root:
        raise InvalidInputError("path escape detected")
    data = source.encode("utf-8")
    fd, tmp_name = tempfile.mkstemp(prefix=f".{name}.", suffix=".tmp", dir=root)
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp_path, target)
    finally:
        if tmp_path.exists():
            tmp_path.unlink(missing_ok=True)
    return target
